package gato.Logica;

import java.nio.file.*;
import java.sql.*;
import java.util.*;
import javax.persistence.*;

/** Base de prueba persistente local compartida por JDBC y las pantallas JPA. */
public final class LocalDatabase {
    private static EntityManagerFactory factory;
    private LocalDatabase() { }

    private static String url() {
        Path directorio = Paths.get(System.getProperty("gato.data", "data")).toAbsolutePath();
        try { Files.createDirectories(directorio); }
        catch (java.io.IOException e) { throw new IllegalStateException("No se pudo crear la carpeta de datos", e); }
        return "jdbc:h2:" + directorio.resolve("gato")
                + ";MODE=MSSQLServer;INIT=CREATE SCHEMA IF NOT EXISTS dbo\\;SET SCHEMA dbo";
    }

    public static Connection open() throws SQLException {
        Connection c = DriverManager.getConnection(url(), "sa", "");
        try (Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS dbo.Jugadores (ID_Jugador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "Jugador VARCHAR(255) NOT NULL, Ganes INT DEFAULT 0, Perdidas INT DEFAULT 0, Empates INT DEFAULT 0)");
            s.execute("CREATE TABLE IF NOT EXISTS dbo.Juego (F1 INT,F2 INT,F3 INT,F4 INT,F5 INT,F6 INT,F7 INT,F8 INT,F9 INT,"
                    + "Jugador1 VARCHAR(255),Ganados1 INT,Empates1 INT,Perdidos1 INT,Ficha1 INT,Turno1 BOOLEAN,"
                    + "Jugador2 VARCHAR(255),Ganados2 INT,Empates2 INT,Perdidos2 INT,Ficha2 INT,Turno2 BOOLEAN)");
        } catch (SQLException e) { c.close(); throw e; }
        return c;
    }

    public static synchronized EntityManager entityManager() {
        if (factory == null) {
            try (Connection ignored = open()) { }
            catch (SQLException e) { throw new IllegalStateException("No se pudo inicializar Gato", e); }
            Map<String, Object> properties = new HashMap<>();
            properties.put("javax.persistence.jdbc.driver", "org.h2.Driver");
            properties.put("javax.persistence.jdbc.url", url());
            properties.put("javax.persistence.jdbc.user", "sa");
            properties.put("javax.persistence.jdbc.password", "");
            properties.put("eclipselink.weaving", "false");
            properties.put("eclipselink.ddl-generation", "none");
            factory = Persistence.createEntityManagerFactory("GatoLocal", properties);
        }
        return factory.createEntityManager();
    }
}
